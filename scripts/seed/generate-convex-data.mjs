#!/usr/bin/env node
/**
 * Turn the catalogue + fetched photo manifest into code the Convex deployment
 * can import.
 *
 * Why generated code instead of a giant mutation argument: a 136-listing seed is
 * far larger than a comfortable function argument, and bundling it keeps the
 * operator command a single `convex run` with no upload step. The file is
 * committed so the deploy is reproducible.
 *
 * Writes:
 *   convex/seedData.ts        listings, owner slots, photo metadata
 *   lib/image-credits.ts      attribution for /credits
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..", "..");
const CATALOG = join(ROOT, "scripts", "seed", "catalog.json");
const MANIFEST = join(ROOT, ".seed-cache", "manifest.json");
const OUT_DATA = join(ROOT, "convex", "seedData.ts");
const OUT_CREDITS = join(ROOT, "lib", "image-credits.ts");

const catalog = JSON.parse(readFileSync(CATALOG, "utf8"));
const manifest = JSON.parse(readFileSync(MANIFEST, "utf8"));
const byName = new Map(manifest.listings.map((row) => [row.name, row]));

const OWNER_SLOTS = 4;
const problems = [];
const listings = catalog.listings.map((listing, index) => {
  const fetched = byName.get(listing.name);
  if (fetched === undefined) {
    problems.push(`no fetched images for "${listing.name}"`);
    return null;
  }
  if (fetched.images.length === 0) problems.push(`no images for "${listing.name}"`);
  return {
    name: listing.name,
    category: listing.category,
    condition: listing.condition,
    description: listing.description,
    valueCents: listing.valueCents,
    dailyRateCents: listing.dailyRateCents,
    status: listing.status,
    ownerSlot: index % OWNER_SLOTS,
    // Spread the "listed N days ago" line across the last five months.
    listedDaysAgo: 1 + ((index * 37 + 11) % 148),
    images: fetched.images.map(({ objectKey, contentType, byteSize, width, height }) => ({
      objectKey,
      contentType,
      byteSize,
      width,
      height,
    })),
  };
});

if (problems.length > 0) {
  console.error(`seed data incomplete (${problems.length}):`);
  for (const problem of problems) console.error(`  - ${problem}`);
  process.exit(1);
}

const header = `// GENERATED by scripts/seed/generate-convex-data.mjs — do not edit by hand.
// Source: scripts/seed/catalog.json + .seed-cache/manifest.json.
//
// ${listings.length} listings, ${listings.reduce((sum, row) => sum + row.images.length, 0)} photos.

import type { Category, Condition, ToolStatus } from "./lib/constants";

export interface SeedImage {
  objectKey: string;
  contentType: string;
  byteSize: number;
  width: number;
  height: number;
}

export interface SeedListing {
  name: string;
  category: Category;
  condition: Condition;
  description: string;
  valueCents: number;
  dailyRateCents: number;
  status: ToolStatus;
  /** Which of the deployment's owners (sorted by email) should own it. */
  ownerSlot: number;
  /** Drives the varied "listed N days ago" line. */
  listedDaysAgo: number;
  images: SeedImage[];
}

`;

const body = `export const SEED_LISTINGS: SeedListing[] = ${JSON.stringify(listings, null, 2)};\n\nexport const SEED_OWNER_SLOTS = ${OWNER_SLOTS};\n`;
writeFileSync(OUT_DATA, `${header}${body}`);

const seen = new Map();
for (const listing of listings) {
  const fetched = byName.get(listing.name);
  for (const image of fetched.images) {
    const credit = image.credit ?? {};
    const key = credit.pageid ?? image.objectKey;
    if (seen.has(key)) continue;
    seen.set(key, {
      title: credit.title ?? "Untitled",
      source: credit.source ?? "",
      license: credit.license ?? "",
      licenseUrl: credit.licenseUrl ?? "",
      artist: credit.artist ?? "",
    });
  }
}
const credits = [...seen.values()].sort((a, b) => a.title.localeCompare(b.title));
const creditsFile = `// GENERATED by scripts/seed/generate-convex-data.mjs — do not edit by hand.
//
// Every seed photo comes from Wikimedia Commons. Formats were converted to WebP
// and images resized; the licence and attribution below still apply, which is
// why they are rendered on /credits.

export interface ImageCredit {
  title: string;
  source: string;
  license: string;
  licenseUrl: string;
  artist: string;
}

export const IMAGE_CREDITS: ImageCredit[] = ${JSON.stringify(credits, null, 2)};
`;
writeFileSync(OUT_CREDITS, creditsFile);

console.log(`wrote ${OUT_DATA} (${listings.length} listings)`);
console.log(`wrote ${OUT_CREDITS} (${credits.length} photo credits)`);
